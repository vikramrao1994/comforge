/**
 * `bun tooling/docs/generate.ts [--check]` — writes the reference inventories in
 * `docs/reference/inventory/` from the authoritative contracts (`contracts.ts`). With
 * `--check` it writes nothing and exits 1 when a committed file differs from what the
 * contracts produce, so a changed command, flag, tool, error code, configuration key or
 * export cannot ship with stale reference tables.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import {
  apiContracts,
  cliContracts,
  configContracts,
  mcpContracts,
  PACKAGES,
  packageVersion,
  REPO,
} from "./contracts";

export const GENERATED_DIR = "docs/reference/inventory";
const HEADER = (source: string) =>
  `<!-- Generated by tooling/docs/generate.ts from ${source}. Do not edit; run \`bun run docs:generate\`. -->\n\n`;
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

export async function renderAll(): Promise<Record<string, string>> {
  const cli = await cliContracts();
  const mcp = await mcpContracts();
  const cfg = await configContracts();
  const api = await apiContracts();
  const out: Record<string, string> = {};

  out["cli-commands.md"] =
    HEADER("packages/cli/src/commands/agent.ts (COMMANDS)") +
    `# CLI commands (\`@comforge/cli\` ${cli.version})\n\n` +
    `Global flags: ${cli.globalFlags.map((f) => `\`${f}\``).join(", ")}.\n\n` +
    "Flags are what the argument parser accepts (`KNOWN_FLAGS`); a flag marked * is accepted but not shown in the command's usage line.\n\n" +
    "| Command | Usage | Flags | Writes | Dry run by default |\n|---|---|---|---|---|\n" +
    cli.commands
      .map(
        (c) =>
          `| \`${c.name}\` | \`comforge ${cell(c.usage)}\` | ${c.flags.map((f) => `\`${f}\`${c.usageOmits.includes(f) ? "*" : ""}`).join(" ") || "—"} | ${cell(c.writes)} | ${c.dryRunByDefault ? "yes" : "—"} |`,
      )
      .join("\n") +
    "\n";

  out["cli-errors.md"] =
    HEADER("packages/cli/src/errors.ts (ERROR_CODES, EXIT)") +
    `# CLI error codes and exit statuses (\`@comforge/cli\` ${cli.version})\n\n` +
    "| Exit | Name |\n|---|---|\n" +
    Object.entries(cli.exitCodes)
      .map(([n, v]) => `| ${v} | \`${n}\` |`)
      .join("\n") +
    "\n\n| Error code | Exit status |\n|---|---|\n" +
    Object.entries(cli.errorCodes)
      .map(([n, v]) => `| \`${n}\` | ${v} |`)
      .join("\n") +
    "\n";

  out["mcp-tools.md"] =
    HEADER("packages/mcp/src/contracts.ts (TOOLS, PROFILES), packages/mcp/src/bin.ts") +
    `# MCP tools (\`@comforge/mcp\` ${mcp.version})\n\n` +
    `Profiles: ${mcp.profiles.map((p) => `\`${p}\``).join(", ")}. ` +
    `Launch flags of \`comforge-mcp\` (stdio): ${mcp.binFlags.map((f) => `\`${f}\``).join(", ")}. ` +
    `Tools a checkout-free remote host serves: ${mcp.remoteReadTools.map((t) => `\`${t}\``).join(", ")}.\n\n` +
    "| Tool | Title | Profiles | Runs repository commands | May write to GitHub | Destructive | Description |\n|---|---|---|---|---|---|---|\n" +
    mcp.tools
      .map(
        (t) =>
          `| \`${t.name}\` | ${cell(t.title)} | ${t.profiles.join(", ")} | ${t.executes ? "yes" : "—"} | ${t.writes ? "yes" : "—"} | ${t.destructive ? "yes" : "—"} | ${cell(t.description)} |`,
      )
      .join("\n") +
    "\n";

  out["mcp-errors.md"] =
    HEADER("packages/mcp/src/results.ts (MCP_CODES)") +
    `# MCP error codes (\`@comforge/mcp\` ${mcp.version})\n\n` +
    "MCP results also carry every CLI error code (see [cli-errors.md](cli-errors.md)); these are the server's own.\n\n" +
    "| Code | Meaning |\n|---|---|\n" +
    Object.entries(mcp.errorCodes)
      .map(([n, m]) => `| \`${n}\` | ${cell(m)} |`)
      .join("\n") +
    "\n";

  out["configuration.md"] =
    HEADER("@comforge/cli/config (configJsonSchema)") +
    `# Configuration sections and keys (\`comforge-config/v1\`, \`@comforge/cli\` ${cli.version})\n\n` +
    "`comforge schema config` prints the full JSON Schema.\n\n" +
    "| Section | Required | Keys |\n|---|---|---|\n" +
    cfg.sections
      .map(
        (s) =>
          `| \`${s.name}\` | ${s.required ? "yes" : "—"} | ${s.keys.map((k) => `\`${k}\``).join(", ") || "—"} |`,
      )
      .join("\n") +
    "\n";

  const bySpec = new Map<string, typeof api>();
  for (const e of api) bySpec.set(e.specifier, [...(bySpec.get(e.specifier) ?? []), e]);
  out["api.md"] =
    HEADER("the runtime exports of every published subpath (package.json exports)") +
    "# Programmatic API inventory\n\n" +
    "Every runtime export of every published subpath. Types are exported alongside and listed in each package's `dist/*.d.ts`. Summaries are the first sentence of the source doc comment.\n\n" +
    PACKAGES.map(
      (id) =>
        `## \`@comforge/${id}\` ${packageVersion(id)}\n\n` +
        [...bySpec.entries()]
          .filter(([s]) => s === `@comforge/${id}` || s.startsWith(`@comforge/${id}/`))
          .map(
            ([s, entries]) =>
              `### \`${s}\`\n\n| Export | Kind | Summary |\n|---|---|---|\n` +
              entries
                .map((e) => `| \`${e.name}\` | ${e.kind} | ${cell(e.summary) || "—"} |`)
                .join("\n"),
          )
          .join("\n\n"),
    ).join("\n\n") +
    "\n";
  return out;
}

export async function checkGenerated(): Promise<string[]> {
  const files = await renderAll();
  const problems: string[] = [];
  for (const [name, text] of Object.entries(files)) {
    const file = path.join(REPO, GENERATED_DIR, name);
    if (!existsSync(file)) problems.push(`${GENERATED_DIR}/${name} is missing`);
    else if (readFileSync(file, "utf8") !== text)
      problems.push(`${GENERATED_DIR}/${name} is stale: run bun run docs:generate`);
  }
  return problems;
}

if (import.meta.main) {
  if (process.argv.includes("--check")) {
    const problems = await checkGenerated();
    for (const p of problems) console.log(p);
    console.log(problems.length ? `FAIL generated (${problems.length})` : "PASS generated");
    process.exit(problems.length ? 1 : 0);
  }
  mkdirSync(path.join(REPO, GENERATED_DIR), { recursive: true });
  for (const [name, text] of Object.entries(await renderAll()))
    writeFileSync(path.join(REPO, GENERATED_DIR, name), text);
  console.log(`wrote ${GENERATED_DIR}/`);
}
